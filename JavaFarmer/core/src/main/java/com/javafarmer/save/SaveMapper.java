package com.javafarmer.save;

import com.javafarmer.progress.DailyChallenges;
import com.javafarmer.progress.Missions;
import com.javafarmer.runtime.ProgramFeature;
import com.javafarmer.world.CropType;
import com.javafarmer.world.Farm;
import com.javafarmer.world.FarmTile;
import com.javafarmer.world.FarmWorld;

import java.util.ArrayList;

/** Converts between the JSON save and the live {@link Farm}, migrating v1 saves on the way in. */
public final class SaveMapper {
    private SaveMapper() {}

    public static Farm toFarm(GameSave save) {
        Farm farm = new Farm(save.worldSeed);
        boolean legacy = save.version < 2;
        farm.coins = Math.max(0, save.coins);
        if (legacy) {
            // v1: one generic seed counter (wheat), cycles instead of ticks, fixed 3x3 farm.
            farm.seeds[CropType.WHEAT.ordinal()] = Math.max(0, save.seeds);
            farm.world.restorePlayer(clamp(save.playerX), clamp(save.playerZ), (long) Math.max(0, save.cycles) * FarmWorld.TICKS_PER_CYCLE);
        } else {
            copy(save.seedStock, farm.seeds);
            copy(save.itemStock, farm.items);
            farm.world.setFarmSize(save.farmSize);
            farm.world.restorePlayer(clamp(save.playerX), clamp(save.playerZ), Math.max(0, save.ticks));
            if (save.unlockedCrops != null) {
                for (String name : save.unlockedCrops) { CropType c = CropType.parse(name); if (c != null) farm.unlocked.add(c); }
            }
            if (save.upgrades != null) {
                for (String name : save.upgrades) { Farm.Upgrade u = Farm.Upgrade.parse(name); if (u != null) farm.upgrades.add(u); }
            }
        }
        // Crops unlocked by completed missions are always available, even if the list was edited.
        int completed = Math.max(0, Math.min(Missions.ALL.size(), save.missionsCompleted));
        for (int i = 0; i < completed; i++) {
            CropType crop = Missions.ALL.get(i).unlockCrop();
            if (crop != null) farm.unlocked.add(crop);
        }
        if (save.tiles != null) {
            int limit = Math.min(save.tiles.size(), 10_000);
            for (int i = 0; i < limit; i++) {
                GameSave.TileSnapshot t = save.tiles.get(i);
                if (t == null) continue;
                if (t.progress < 0) farm.world.restoreTile(t.x, t.z, t.tilled, t.crop, t.growth, t.watered);
                else farm.world.restoreTile(t.x, t.z, t.tilled, t.crop, t.progress, t.waterTicks);
            }
        }
        if (legacy) {
            // The old calendar challenge does not translate; a day-based one is generated by the game.
            save.challengeKind = null;
            save.missionsCompleted = 0;
            save.version = GameSave.CURRENT_VERSION;
        }
        return farm;
    }

    public static void fromFarm(Farm farm, GameSave save) {
        save.version = GameSave.CURRENT_VERSION;
        save.worldSeed = farm.world.seed();
        save.coins = farm.coins;
        save.playerX = farm.world.playerX();
        save.playerZ = farm.world.playerZ();
        save.ticks = farm.world.ticks();
        save.cycles = farm.world.cycles();
        save.farmSize = farm.world.farmSize();
        save.seedStock = farm.seeds.clone();
        save.itemStock = farm.items.clone();
        save.seeds = farm.totalSeeds();
        save.unlockedCrops = farm.unlocked.stream().map(Enum::name).toArray(String[]::new);
        save.upgrades = farm.upgrades.stream().map(Enum::name).toArray(String[]::new);
        save.tiles = new ArrayList<>();
        for (FarmTile tile : farm.world.getTiles().values()) {
            if (!tile.tilled && !tile.hasCrop()) continue;
            GameSave.TileSnapshot snapshot = new GameSave.TileSnapshot();
            snapshot.x = tile.x;
            snapshot.z = tile.z;
            snapshot.tilled = tile.tilled;
            snapshot.crop = tile.crop;
            snapshot.growth = tile.growth;
            snapshot.watered = tile.watered;
            snapshot.progress = tile.progress;
            snapshot.waterTicks = tile.waterTicks;
            save.tiles.add(snapshot);
        }
    }

    // ----- daily challenge <-> save fields

    public static DailyChallenges.Challenge challenge(GameSave save) {
        if (save.challengeKind == null) return null;
        try {
            DailyChallenges.Kind kind = DailyChallenges.Kind.valueOf(save.challengeKind);
            ProgramFeature feature = save.challengeFeature == null || save.challengeFeature.isEmpty()
                    ? null : ProgramFeature.valueOf(save.challengeFeature);
            return new DailyChallenges.Challenge(Math.max(1, save.challengeDay), Math.max(1, save.challengeTier), kind,
                    save.challengeCrop == null ? "" : save.challengeCrop, Math.max(1, save.challengeAmount),
                    Math.max(0, save.challengeSize), feature, save.challengeSingleRun,
                    Math.max(0, save.challengeRewardCoins), Math.max(0, save.challengeRewardPoints));
        } catch (IllegalArgumentException ex) {
            return null;
        }
    }

    public static void storeChallenge(DailyChallenges.Challenge c, GameSave save) {
        save.challengeDay = c.day();
        save.challengeTier = c.tier();
        save.challengeKind = c.kind().name();
        save.challengeCrop = c.crop();
        save.challengeAmount = c.amount();
        save.challengeSize = c.size();
        save.challengeFeature = c.feature() == null ? "" : c.feature().name();
        save.challengeSingleRun = c.singleRun();
        save.challengeRewardCoins = c.rewardCoins();
        save.challengeRewardPoints = c.rewardPoints();
        save.challengeProgress = 0;
        save.challengeClaimed = false;
    }

    private static void copy(int[] from, int[] to) {
        if (from == null) return;
        for (int i = 0; i < to.length && i < from.length; i++) to[i] = Math.max(0, Math.min(1_000_000, from[i]));
    }

    private static int clamp(int value) {
        return Math.max(-1_000_000, Math.min(1_000_000, value));
    }
}
